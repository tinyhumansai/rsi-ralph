//! Loads a built module through the real `TinyBus` dynamic loader.

use std::io;
use std::path::PathBuf;
use std::time::Duration;

use tinybus::Connection;
use tinybus::broker::Broker;
use tinybus::module::ModuleHost;
use tinybus::transport::memory::MemoryBus;
use tinyrsi::{
    GradeEntry, LineageAppendRequest, LineageAppendResponse, LineageHeadRequest,
    LineageHeadResponse, Verdict, names,
};

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let module = module_argument()?;
    let bus = MemoryBus::new();
    let broker = Broker::new();
    let broker_task = broker.spawn(bus.clone());
    let module_host = ModuleHost::new(broker);
    let info = module_host.load_file(&module)?;

    if info.name != env!("CARGO_PKG_NAME") {
        return Err(io::Error::other(format!(
            "loaded module `{}` instead of `{}`",
            info.name,
            env!("CARGO_PKG_NAME")
        ))
        .into());
    }

    let client = Connection::connect(bus.connect().await?).await?;
    tokio::time::timeout(Duration::from_secs(5), async {
        loop {
            let claimed = client.list_names().await?;
            if claimed.iter().any(|name| name.as_str() == names::INTERFACE) {
                return tinybus::Result::Ok(());
            }
            tokio::task::yield_now().await;
        }
    })
    .await??;

    let proxy = client.proxy(names::INTERFACE, names::OBJECT_PATH, names::INTERFACE)?;
    let empty: LineageHeadResponse = proxy
        .call(names::methods::HEAD, (LineageHeadRequest::new(),))
        .await?;
    if empty.entry.is_some() {
        return Err(io::Error::other("a fresh module reported a non-empty lineage head").into());
    }

    let entry = GradeEntry::new(
        0,
        "sha256:verify",
        0.703,
        Verdict::Accepted,
        "release verifier",
    );
    let recorded: LineageAppendResponse = proxy
        .call(names::methods::APPEND, (LineageAppendRequest::new(entry),))
        .await?;
    if !recorded.recorded {
        return Err(io::Error::other("the module did not record the baseline entry").into());
    }

    println!(
        "verified {} as TinyBus module `{}`",
        module.display(),
        info.name
    );
    broker_task.abort();
    Ok(())
}

fn module_argument() -> Result<PathBuf, io::Error> {
    std::env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .ok_or_else(|| {
            io::Error::new(
                io::ErrorKind::InvalidInput,
                "usage: cargo run --example verify_module -- <module-path>",
            )
        })
}
